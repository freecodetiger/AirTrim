        特点：

        * 有具体身份、场景或处境
        * 不夸张
        * 有真实感
        * 让人产生“我也遇到过”的感觉

        ### 方向二：冲突/反差型

        抓住视频中最强的矛盾、反差或意外。

        特点：

        * 前半句制造认知
        * 后半句形成反转
        * 可以适当制造悬念
        * 不允许标题党式虚假夸张

        ### 方向三：讨论型

        把视频中的核心问题转化成一个容易引发评论的问题。

        特点：

        * 适合评论区讨论
        * 尽量让目标用户能够回答
        * 可以使用“到底”“为什么”“是不是”等表达
        * 问题必须真实来源于视频内容

        标题要短、口语化、像真人会发出来的内容，不要写成新闻标题或营销文案。

        ## 文案要求

        生成 1 段适合直接发布的抖音配文。

        文案不是字幕的简单复述，而是对视频内容的二次包装。

        推荐结构：

        **第一段：** 用一句话快速交代视频中的核心处境或冲突。

        **第二段：** 补充视频中的关键经历，让读者即使不看字幕也能快速理解视频在讲什么。

        **第三段：** 提炼作者此刻最真实的情绪、疑问或思考。

        **最后：** 如果视频中存在一个开放性问题，将它自然地抛给评论区，引导有相关经历的人分享自己的情况。

        整体应该像一个真实的人发朋友圈/抖音，而不是品牌官方账号。

        ## 语言风格

        * 口语化
        * 简洁
        * 有人味
        * 不要过度鸡汤
        * 不要故意“高级”
        * 不要使用营销腔
        * 不要堆砌 emoji
        * 不要为了吸引点击而制造字幕中不存在的冲突
        * 可以保留视频作者原本的说话习惯和情绪
        * 如果原字幕存在明显的焦虑、困惑、兴奋、吐槽等情绪，应尽量保留这种情绪

        尤其避免：

        > “今天给大家分享一个非常重要的话题……”

        > “在当今这个快速发展的时代……”

        > “如果你也正在经历……那么一定不要错过……”

        这类模板化 AI 文案。

        ## 标签

        根据视频实际内容生成 3～6 个相关标签。

        优先选择：

        1. 视频所属领域
        2. 视频涉及的具体主题
        3. 目标人群
        4. 用户常用搜索词

        不要为了凑数量添加与视频无关的热门标签。

        ## 输出要求

        最终只输出以下内容：

        ### 标题

        **真实记录型：**
        ...

        **冲突/反差型：**
        ...

        **讨论型：**
        ...

        ### 文案

        ...

        ### 标签

        #标签 1 #标签 2 #标签 3 ...

        不要输出你的分析过程，不要解释为什么这样写，也不要复述字幕。
        """
    )

