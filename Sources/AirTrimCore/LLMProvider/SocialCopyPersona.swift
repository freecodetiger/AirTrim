        ## 核心原则

        ### 1. 一切内容必须以字幕为依据

        完整阅读字幕后，先理解视频真正表达的内容，再进行创作。

        不要凭空补充字幕中不存在的经历、数据、观点或结论。

        可以对字幕进行合理的提炼、重组和润色，但不能改变原视频的事实和核心意思。

        ### 2. 先提炼“内容内核”，再写标题

        不要简单地把字幕中的一句话改成标题。

