import Foundation

/// 抖音文案人设模板：纯值类型，字段与 `docs/design/personas/{slug}.md` 一一对应。
/// 由「共享任务 prompt + 人设块」拼成完整 system prompt（见 `SocialCopywriter`）。
/// 只定义「表达方式」，不写任务流程与输出格式——那属于 taskPrompt。
public struct SocialCopyPersona: Sendable, Equatable, Identifiable {
    public let id: String            // slug：tech-growth 等（md 标题里的 slug）
    public let displayName: String   // 「技术成长派」
    public let description: String   // 选择器副标题（一句话）

    // —— 以下字段与 md 各节一一对应 ——
    public let audience: String       // 受众画像
    public let valueTypes: String     // 内容价值类型
    public let titleHooks: String     // 标题钩子（类型 × 范例）
    public let copyTones: String      // 文案语气（角度 × 范例）
    public let tags: String           // 标签方向（精准/泛流量/身份）
    public let platformAnchor: String // 抖音平台锚点（3 秒钩子/口播风格/封面字）
    public let redLines: String       // 红线（禁止 + 反例）
    public let tasteCheck: String     // 语感判据（自测句）
    /// 自包含完整 system prompt（非 nil 时 `SocialCopywriter.systemPrompt` 直接用它，
    /// 不再拼 taskPrompt + promptBlock）。用于结构自成一体的人设（如 general 换了整份 prompt）。
    public let fullPrompt: String?

    public init(id: String, displayName: String, description: String,
                audience: String, valueTypes: String, titleHooks: String,
                copyTones: String, tags: String, platformAnchor: String,
                redLines: String, tasteCheck: String,
                fullPrompt: String? = nil) {
        self.id = id
        self.displayName = displayName
        self.description = description
        self.audience = audience
        self.valueTypes = valueTypes
        self.titleHooks = titleHooks
        self.copyTones = copyTones
        self.tags = tags
        self.platformAnchor = platformAnchor
        self.redLines = redLines
        self.tasteCheck = tasteCheck
        self.fullPrompt = fullPrompt
    }

    /// 渲染为人设指令块，与 taskPrompt 拼接后作为 system prompt。
    public var promptBlock: String {
        """
        你是深耕「\(displayName)」赛道的内容运营专家。\(description)

        ## 受众画像
        \(audience)

        ## 内容价值类型
        \(valueTypes)

        ## 标题钩子（从下列类型中挑选最合适的，每类各出 1 个方案）
        \(titleHooks)

        ## 文案语气（每个角度各出 1 个方案）
        \(copyTones)

        ## 标签方向（示例词方向，据此发散，不要照抄）
        \(tags)

        ## 抖音平台锚点
        \(platformAnchor)

        ## 红线（绝对禁止，违反即整篇不合格）
        \(redLines)

        ## 语感判据
        \(tasteCheck)
        """
    }
}

